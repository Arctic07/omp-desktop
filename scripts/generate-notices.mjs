#!/usr/bin/env node
// Generates THIRD_PARTY_LICENSES.md: one section per distinct license text found in the workspace's
// production dependency tree, with the packages that ship it.
//
// The inventory is `pnpm licenses list --prod --json`, so the file follows the lockfile rather than a
// hand-kept list. Texts are read from each package's own license files and deduplicated by content;
// a package that ships none is listed with its declared identifier and author instead, never with an
// invented copyright line. The build inlines a subset of these packages and keeps some external; the
// file covers the tree, and THIRD_PARTY_NOTICES.md carries the headline attribution for the engine.
//
// `--check` compares the generated text with disk and fails when they differ, which is the gate
// (`check:repo`): a dependency bump that changes a license must show up as a reviewable diff.

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const OUTPUT = 'THIRD_PARTY_LICENSES.md'
const LICENSE_FILE = /^(?:licen[cs]e|copying|notice|unlicense|copyright)/i
const NOT_A_TEXT = /\.spdx$/i

function inventory() {
  const json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 128 * 1024 * 1024,
  })
  const byIdentifier = JSON.parse(json)
  const packages = []
  for (const [declared, entries] of Object.entries(byIdentifier)) {
    for (const entry of entries) {
      packages.push({
        declared: entry.license ?? declared,
        name: entry.name,
        versions: entry.versions ?? [],
        author: entry.author ?? null,
        homepage: entry.homepage ?? null,
        paths: entry.paths ?? [],
      })
    }
  }
  return packages
}

function licenseTexts(dir) {
  let names
  try {
    names = readdirSync(dir).filter(
      (name) => LICENSE_FILE.test(name) && !NOT_A_TEXT.test(name) && statSync(path.join(dir, name)).isFile(),
    )
  } catch {
    return null
  }
  if (names.length === 0) return null
  return names.sort().map((name) => {
    const buffer = readFileSync(path.join(dir, name))
    const text = buffer[0] === 0xff && buffer[1] === 0xfe ? buffer.toString('utf16le') : buffer.toString('utf8')
    return text.replace(/\r\n?/g, '\n').replace(/^\n+/, '').replace(/\n+$/, '')
  })
}

function label(pkg) {
  return pkg.versions.length === 0 ? pkg.name : `${pkg.name}@${pkg.versions.join(',')}`
}

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** One group per distinct text; `packages` and `declared` are sets so a shared file appears once. */
const groups = new Map()
const missing = new Map()
for (const pkg of inventory()) {
  let texts = null
  for (const dir of pkg.paths) {
    texts = licenseTexts(dir)
    if (texts !== null) break
  }
  if (texts === null) {
    const key = pkg.declared
    if (!missing.has(key)) missing.set(key, [])
    missing.get(key).push(pkg)
    continue
  }
  for (const text of texts) {
    if (!groups.has(text)) groups.set(text, { packages: new Set(), declared: new Set() })
    groups.get(text).packages.add(label(pkg))
    groups.get(text).declared.add(pkg.declared)
  }
}

function fenceFor(text) {
  const longest = (text.match(/`+/g) ?? []).reduce((longest, run) => Math.max(longest, run.length), 0)
  return '`'.repeat(Math.max(3, longest + 1))
}

const sections = [...groups.entries()]
  .map(([text, group]) => {
    const names = [...group.packages].sort(byCodeUnit)
    const declared = [...group.declared].sort(byCodeUnit).join(' / ')
    const title = names.length === 1 ? names[0] : `${names[0]} and ${names.length - 1} more`
    const rest = names.slice(1)
    const also = rest.length === 0 ? '' : `\n\nAlso applies to:\n\n${rest.map((name) => `- \`${name}\``).join('\n')}`
    const fence = fenceFor(text)
    return `## ${title}\n\nDeclared license: ${declared}${also}\n\n${fence}text\n${text}\n${fence}\n`
  })
  .sort(byCodeUnit)

const missingSections = [...missing.entries()]
  .sort(([a], [b]) => byCodeUnit(a, b))
  .map(([declared, packages]) => {
    const entries = packages
      .sort((a, b) => byCodeUnit(label(a), label(b)))
      .map((pkg) => {
        const author = pkg.author === null ? '' : ` — author \`${pkg.author}\``
        const homepage = pkg.homepage === null ? '' : ` — ${pkg.homepage.replace(/^git\+/, '')}`
        return `- \`${label(pkg)}\`${author}${homepage}`
      })
    return `## No license file shipped (${declared})\n\nThese packages declare ${declared} but ship no license text of their own in the installed tree:\n\n${entries.join('\n')}\n`
  })

const header = `# Third-party licenses

Generated by \`scripts/generate-notices.mjs\` from the workspace's production dependency tree (\`pnpm licenses list --prod\`). Do not edit by hand: run \`pnpm notices:generate\`.

The desktop build inlines a subset of these packages into its artifacts and keeps some external; the list covers the production tree. The engine's headline attribution and the MiSans font notice are in [\`THIRD_PARTY_NOTICES.md\`](THIRD_PARTY_NOTICES.md).
`

const output = `${[header, ...sections, ...missingSections].filter((part) => part !== '').join('\n')}`

if (process.argv.includes('--check')) {
  const current = existsSync(path.join(ROOT, OUTPUT)) ? readFileSync(path.join(ROOT, OUTPUT), 'utf8') : null
  if (current !== output) {
    console.error(`${OUTPUT} is stale — run \`pnpm notices:generate\` and commit the result`)
    process.exit(1)
  }
  console.log(`notices: ${groups.size} license text(s) across ${sections.length} section(s) match ${OUTPUT}`)
} else {
  writeFileSync(path.join(ROOT, OUTPUT), output)
  console.log(`notices: wrote ${OUTPUT} — ${groups.size} license text(s), ${missing.size} declared identifier(s) without a file`)
}
